import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:flutter_screenutil/flutter_screenutil.dart';
import 'package:flutter_dotenv/flutter_dotenv.dart';
import 'package:firebase_core/firebase_core.dart';

import 'firebase_options.dart';
import 'providers/theme_provider.dart';
import 'providers/cart_provider.dart';
import 'screens/splash_screen.dart';
import 'screens/signin_screen.dart';
import 'screens/signup_screen.dart';
import 'screens/login_loading_screen.dart';
import 'screens/home_screen.dart';

void main() async {
  // Needed because we now do async setup (loading .env) before runApp.
  WidgetsFlutterBinding.ensureInitialized();

  // Enhancement 1 & 2: load HOST from assets/.env so UserService's
  // "$host/auth/login" calls actually resolve — constants.dart's `host`
  // variable depends on dotenv already being loaded before any network
  // call is made.
  await dotenv.load(fileName: "assets/.env");

  // Lab Activity 5: initialize Firebase (options generated by
  // `flutterfire configure`) before runApp.
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  runApp(
    MultiProvider(
      providers: [
        ChangeNotifierProvider(create: (_) => ThemeProvider()),
        ChangeNotifierProvider(create: (_) => CartProvider()),
      ],
      child: const MyApp(),
    ),
  );
}

class MyApp extends StatelessWidget {
  const MyApp({Key? key}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    final themeProvider = Provider.of<ThemeProvider>(context);

    return ScreenUtilInit(
      designSize: const Size(360, 690),
      minTextAdapt: true,
      splitScreenMode: true,
      builder: (context, child) {
        return MaterialApp(
          title: 'Advanced Mobile Programming Project',
          theme: themeProvider.currentTheme,
          debugShowCheckedModeBanner: false,

          // Enhancement 1 & 2: Splash checks persistent auth, then routes
          // to either Sign In or Home.
          initialRoute: '/',
          routes: {
            '/': (context) => const SplashScreen(),
            '/signin': (context) => const SignInScreen(),
            '/signup': (context) => const SignUpScreen(),
            '/login-loading': (context) {
              final userData =
                  (ModalRoute.of(context)?.settings.arguments
                          as Map<String, dynamic>?) ??
                      const <String, dynamic>{};
              return LoginLoadingScreen(userData: userData);
            },
          },
          onGenerateRoute: (settings) {
            if (settings.name == '/home') {
              // Enhancement 3: '/home' always receives the logged-in
              // user's data as its route arguments (either fresh from
              // SignInScreen, or restored by SplashScreen from
              // SharedPreferences).
              final userData =
                  (settings.arguments as Map<String, dynamic>?) ??
                  const <String, dynamic>{};
              return MaterialPageRoute(
                builder: (_) => HomeScreen(userData: userData),
              );
            }
            return null;
          },
        );
      },
    );
  }
}
